function createForecastPoints(
  range: ForecastRange,
  points: SalesForecastInput[]
): SalesForecastPoint[] {
  return points.map((point, index) => ({
    ...point,
    id: `${range}-${point.date}-${point.productName}-${index}`,
    error: point.actual - point.prediction,
  }));
}


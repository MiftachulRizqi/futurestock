export type ForecastRange = "daily" | "weekly" | "monthly";

export type SalesForecastPoint = {
  id: string;
  date: string;
  label: string;
  period: string;
  category: string;
  productName: string;
  actual: number;
  prediction: number;
  error: number;
};

type SalesForecastInput = Omit<SalesForecastPoint, "id" | "error">;

